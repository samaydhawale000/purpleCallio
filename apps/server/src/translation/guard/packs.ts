/**
 * Built-in PurpleLex starter packs (GET /translation/lexicons/packs).
 * Generic, factual terms only — no product brands. Mostly DO_NOT_TRANSLATE
 * (acronyms, units, drug and technical names); a few TRANSLATE_AS where a
 * standard Hindi term exists.
 */
import type { LexiconTerm } from './lexicon-correct';

export interface IndustryPack {
  industry: 'healthcare' | 'legal' | 'saas' | 'finance' | 'ecommerce';
  name: string;
  description: string;
  terms: LexiconTerm[];
}

const keep = (...terms: string[]): LexiconTerm[] =>
  terms.map((term) => ({ term, kind: 'DO_NOT_TRANSLATE' as const }));

const as = (
  term: string,
  translations: Record<string, string>,
): LexiconTerm => ({
  term,
  kind: 'TRANSLATE_AS',
  translations,
});

